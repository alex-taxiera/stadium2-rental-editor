#!/usr/bin/env python3
"""Generate the key table for the rental editor's nickname keyboard.

The keyboard offers what the Game Boy nickname screens can type: the Gold/Silver/Crystal
layout, plus the male and female signs from Red/Blue/Yellow. Two pages of four rows of
nine keys, upper case and lower case.

The game keeps names in its own character codes and converts them to Game Boy codes
when a team is registered (table D_80097380 for English). KEYS gives both codes for
every key, so the tests can check them against the ROM.

    tools/mod/gen_name_keys.py     # writes mod/data/name_keys.inc.c

Standard library only.
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "mod" / "data" / "name_keys.inc.c"

# One string per row. {PK} and {MN} are the single-tile ligatures; an unused cell is a
# space, which types a space as it does on the Game Boy.
UPPER = ["ABCDEFGHI",
         "JKLMNOPQR",
         "STUVWXYZ ",
         "-?!/.,♂♀ "]
LOWER = ["abcdefghi",
         "jklmnopqr",
         "stuvwxyz ",
         "×():;[]{PK}{MN}"]
PAGES = [UPPER, LOWER]
ROWS, COLUMNS = 4, 9

# key -> (the game's code, the Game Boy's code, name for comments)
SPECIAL = {
    " ": (0x20, 0x7F, "space"),
    "(": (0x28, 0x9A, "("), ")": (0x29, 0x9B, ")"), ":": (0x3A, 0x9C, ":"), ";": (0x3B, 0x9D, ";"),
    "[": (0x5B, 0x9E, "["), "]": (0x5D, 0x9F, "]"),
    "{PK}": (0xBC, 0xE1, "PK"), "{MN}": (0xBD, 0xE2, "MN"),
    "-": (0x2D, 0xE3, "-"), "?": (0x3F, 0xE6, "?"), "!": (0x21, 0xE7, "!"), ".": (0x2E, 0xE8, "."),
    "♂": (0xA9, 0xEF, "male"), "×": (0xD7, 0xF1, "x"), "/": (0x2F, 0xF3, "/"), ",": (0x2C, 0xF4, ","),
    "♀": (0xBE, 0xF5, "female"),
}
KEYS = dict(SPECIAL)
for i in range(26):
    KEYS[chr(ord("A") + i)] = (ord("A") + i, 0x80 + i, chr(ord("A") + i))
    KEYS[chr(ord("a") + i)] = (ord("a") + i, 0xA0 + i, chr(ord("a") + i))


def split_row(row: str) -> list:
    """The keys of a row, with {..} names kept whole."""
    keys, i = [], 0
    while i < len(row):
        end = row.index("}", i) + 1 if row[i] == "{" else i + 1
        keys.append(row[i:end])
        i = end
    return keys


def pages() -> list:
    """Every page as rows of keys, checked for shape."""
    out = []
    for page in PAGES:
        rows = [split_row(row) for row in page]
        if len(rows) != ROWS or any(len(row) != COLUMNS for row in rows):
            raise ValueError(f"every page must be {ROWS} rows of {COLUMNS} keys")
        for row in rows:
            for key in row:
                if key not in KEYS:
                    raise ValueError(f"no character code for key {key!r}")
        out.append(rows)
    return out


def render() -> str:
    lines = [
        "// Generated by tools/mod/gen_name_keys.py. Do not edit by hand.",
        "// The nickname keyboard, as [page][row][column] in the game's character codes.",
        "// Page 0 is upper case and page 1 lower case: the Gold/Silver/Crystal nickname",
        "// screen, plus the male and female signs from Red/Blue/Yellow.",
        f"static const u8 sNameKeys[{len(PAGES)}][{ROWS}][{COLUMNS}] = {{",
    ]
    for page in pages():
        lines.append("    {")
        for row in page:
            codes = ", ".join(f"0x{KEYS[key][0]:02X}" for key in row)
            names = " ".join(KEYS[key][2] for key in row)
            lines.append(f"        {{ {codes} }}, // {names}")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    DEFAULT_OUT.write_text(render(), encoding="ascii", newline="\n")
    print(f"wrote {DEFAULT_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
