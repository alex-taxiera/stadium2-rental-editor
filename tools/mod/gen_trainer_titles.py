#!/usr/bin/env python3
"""Generate the list of trainer titles a player can take.

The game titles every trainer on the screens before and after a battle: GYM LEADER,
RIVAL, and for a player always POKeMON TRAINER. The titles are a text bank in the ROM,
numbered as the game's trainer classes are. Many numbers share a title (RIVAL nineteen
times) and the last few have none, so the mod steps through one number per title: the
player's own first, then the rest in the bank's order.

Only the numbers are written out. The mod reads a title's text from the ROM when it
shows it.

    tools/mod/gen_trainer_titles.py     # writes mod/data/trainer_titles.inc.c

Standard library only.
"""

import struct
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BASE_ROM = REPO_ROOT / "baseroms" / "us" / "baserom.z64"
DEFAULT_OUT = REPO_ROOT / "mod" / "data" / "trainer_titles.inc.c"

TITLES_ROM = 0x1D95240   # the bank: a count, that many offsets from here, then the texts
PLAYER_TITLE = 0x29      # POKeMON TRAINER


def titles(rom: bytes) -> list:
    """Every title in the bank, by number."""
    count, = struct.unpack_from(">I", rom, TITLES_ROM)
    offsets = struct.unpack_from(f">{count}I", rom, TITLES_ROM + 4)
    return [rom[TITLES_ROM + o:rom.index(b"\0", TITLES_ROM + o)] for o in offsets]


def choices(rom: bytes) -> list:
    """One number for each different title, the player's own first."""
    bank = titles(rom)
    seen, numbers = {bank[PLAYER_TITLE]}, [PLAYER_TITLE]
    for number, title in enumerate(bank):
        if title.strip() and title not in seen:
            seen.add(title)
            numbers.append(number)
    return numbers


def render(numbers: list) -> str:
    lines = ["// Generated by tools/mod/gen_trainer_titles.py. Do not edit by hand.",
             "// The trainer titles a player can take, as numbers in the game's bank of them:",
             "// one for each different title, the player's own first.",
             "static const u8 sTrainerTitles[] = {"]
    for start in range(0, len(numbers), 12):
        lines.append("    " + ", ".join(f"0x{n:02X}" for n in numbers[start:start + 12]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    out.write_text(render(choices(BASE_ROM.read_bytes())), encoding="ascii", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
